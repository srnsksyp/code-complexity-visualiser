"use client";

import React, { useState } from "react";
import { AnalyzeResponse } from "@/types/analysis";
import { FileText, X, Copy, Check, Download } from "lucide-react";

interface ReportModalProps {
  isOpen: boolean;
  onClose: () => void;
  result: AnalyzeResponse;
  code: string;
}

export const ReportModal: React.FC<ReportModalProps> = ({
  isOpen,
  onClose,
  result,
  code,
}) => {
  const [copied, setCopied] = useState(false);

  if (!isOpen) return null;

  const generateMarkdownReport = () => {
    return `# Code Complexity Analysis Report
Generated by Code Complexity Visualizer (Deterministic AST Analysis Engine)
Date: ${new Date().toISOString()}

## Executive Summary
- **Time Complexity:** ${result.time_complexity}
- **Space Complexity (Auxiliary):** ${result.space_complexity}
- **Static Confidence:** ${result.confidence}

## Code Statistics
- **Total Functions:** ${result.statistics.function_count}
- **Total Loops:** ${result.statistics.loop_count} (For: ${result.statistics.for_loop_count}, While: ${result.statistics.while_loop_count})
- **Conditionals:** ${result.statistics.conditional_count}
- **Max Nesting Depth:** ${result.statistics.max_nesting_depth} levels
- **Recursion Detected:** ${result.statistics.recursion_detected ? "Yes" : "No"} (${result.statistics.recursion_count} recursive calls)
- **Operation Statements:** ${result.statistics.operation_count}
- **Comprehensions:** ${result.statistics.comprehension_count}

## Mathematical Complexity Explanation
${result.complexity_reasoning}

## Detected Static Patterns
${result.detected_patterns.map((p) => `- ${p}`).join("\n")}

## Optimization Considerations
${
  result.optimization_suggestions.length > 0
    ? result.optimization_suggestions.map((s) => `- ${s}`).join("\n")
    : "- No algorithmic bottlenecks detected."
}

## Analyzed Python Code
\`\`\`python
${code}
\`\`\`
`;
  };

  const reportText = generateMarkdownReport();

  const handleCopy = () => {
    navigator.clipboard.writeText(reportText);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const blob = new Blob([reportText], { type: "text/markdown;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = `complexity_report_${Date.now()}.md`;
    link.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/70 backdrop-blur-xs p-4">
      <div className="w-full max-w-2xl bg-zinc-900 border border-zinc-800 rounded-xl shadow-2xl flex flex-col max-h-[85vh]">
        {/* Modal Header */}
        <div className="flex items-center justify-between px-5 py-3 border-b border-zinc-800">
          <div className="flex items-center gap-2 text-zinc-100 font-semibold text-sm">
            <FileText className="w-4 h-4 text-emerald-400" />
            <span>Asymptotic Complexity Report</span>
          </div>
          <div className="flex items-center gap-2">
            <button
              onClick={handleCopy}
              className="flex items-center gap-1 px-2.5 py-1 text-xs bg-zinc-800 hover:bg-zinc-700 text-zinc-200 rounded-lg border border-zinc-700 transition"
            >
              {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
              <span>{copied ? "Copied" : "Copy Markdown"}</span>
            </button>
            <button
              onClick={handleDownload}
              className="flex items-center gap-1 px-2.5 py-1 text-xs bg-emerald-600 hover:bg-emerald-500 text-white rounded-lg transition"
            >
              <Download className="w-3.5 h-3.5" />
              <span>Download .md</span>
            </button>
            <button
              onClick={onClose}
              className="p-1 text-zinc-400 hover:text-zinc-200 transition ml-1"
            >
              <X className="w-4 h-4" />
            </button>
          </div>
        </div>

        {/* Modal Body */}
        <div className="flex-1 overflow-y-auto p-5 font-mono text-xs text-zinc-300 bg-zinc-950/80 leading-relaxed whitespace-pre-wrap select-all">
          {reportText}
        </div>
      </div>
    </div>
  );
};
